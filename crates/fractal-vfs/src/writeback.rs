/// Inode-intent Pending coalescing rules. Returns the outcome and
/// mutates `existing` in place when a merge is possible. Pairs not
/// covered here fall back to inserting a successor intent -- but the
/// initial enabled op set (PutInode + SetAttr) keeps every
/// coalescable combination here.
fn coalesce_inode_pending(existing: &mut InodeOp, new: &InodeOp) -> CoalesceOutcome {
    match (&mut *existing, new) {
        // PutInode + PutInode (same key) ⇒ replace the layout in
        // place (latest wins). Uncommon because FUSE_CREATE is unique
        // per path, but defensive.
        (
            InodeOp::PutInode { .. },
            InodeOp::PutInode {
                parent_key,
                name,
                layout_bytes,
            },
        ) => {
            *existing = InodeOp::PutInode {
                parent_key: parent_key.clone(),
                name: name.clone(),
                layout_bytes: layout_bytes.clone(),
            };
            CoalesceOutcome::ReplacedInPlace
        }
        // PutInode + SetAttr ⇒ Merged. The worker applies the attr
        // mutation when it ships Stage A.
        (InodeOp::PutInode { .. }, InodeOp::SetAttr { .. }) => CoalesceOutcome::Merged,
        // SetAttr + SetAttr ⇒ field-merge.
        (
            InodeOp::SetAttr {
                attrs: existing_attrs,
                ..
            },
            InodeOp::SetAttr {
                attrs: new_attrs, ..
            },
        ) => {
            existing_attrs.merge_from(new_attrs);
            CoalesceOutcome::Merged
        }
        // SetAttr + PutInode shouldn't happen (PutInode is the
        // creation op; if we have a SetAttr Pending, the create
        // already committed). Treat as a successor.
        (InodeOp::SetAttr { .. }, InodeOp::PutInode { .. }) => CoalesceOutcome::Inserted,
    }
}

