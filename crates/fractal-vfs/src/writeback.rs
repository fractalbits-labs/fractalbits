    // ── Pending-data overlay ────────────────────────────────────────

    #[test]
    fn overlay_records_writes_and_grows_file_size() {
        let q = WritebackQueue::new();
        q.overlay_record_write(1, 0, Bytes::from_static(b"abcd"), 4);
        q.overlay_record_write(1, 1, Bytes::from_static(b"xyzw"), 8);
        // Smaller follow-up does not shrink file_size.
        q.overlay_record_write(1, 0, Bytes::from_static(b"ABCD"), 1);

        let ov = q.overlay_for(1).unwrap();
        assert_eq!(ov.file_size, 8);
        assert_eq!(ov.lookup_block(0).unwrap().as_ref(), b"ABCD");
        assert_eq!(ov.lookup_block(1).unwrap().as_ref(), b"xyzw");
        assert!(ov.lookup_block(2).is_none());
        assert!(!ov.block_is_hole(0));
    }

