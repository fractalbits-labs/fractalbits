    #[test]
    fn dep_tracker_multi_predecessor() {
        let q = WritebackQueue::new();
        let p1 = IntentId(1);
        let p2 = IntentId(2);
        let p3 = IntentId(3);
        let d = IntentId(99);
        q.add_dep(d, p1);
        q.add_dep(d, p2);
        q.add_dep(d, p3);
        assert_eq!(q.unmet_deps(d), 3);
        // Commit p1: dependent still has 2 unmet.
        assert!(q.mark_predecessor_committed(p1).is_empty());
        assert_eq!(q.unmet_deps(d), 2);
        // Commit p2 and p3: d is unblocked only on the last.
        assert!(q.mark_predecessor_committed(p2).is_empty());
        let unblocked = q.mark_predecessor_committed(p3);
        assert_eq!(unblocked, vec![d]);
        assert_eq!(q.unmet_deps(d), 0);
    }

