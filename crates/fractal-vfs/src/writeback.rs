    // ── Sync drains ─────────────────────────────────────────────────

    #[test]
    fn cycles_at_or_below_drained_reports_correctly() {
        let q = WritebackQueue::new();
        q.open_cycle(1, Generation(0), 100, 1);
        q.open_cycle(1, Generation(1), 200, 2);
        q.open_cycle(1, Generation(2), 300, 3);

        // Nothing Done yet.
        assert!(!q.cycles_at_or_below_drained(1, Generation(2)));

        // Mark gen 0 + 1 Done; barrier=1 should drain.
        for g in [Generation(0), Generation(1)] {
            q.advance_stage(1, g, FileCommitStage::StageAQueued)
                .unwrap();
            q.advance_stage(1, g, FileCommitStage::Done).unwrap();
        }
        assert!(q.cycles_at_or_below_drained(1, Generation(1)));
        // Barrier=2 still not drained: gen 2 is dirty.
        assert!(!q.cycles_at_or_below_drained(1, Generation(2)));

        // Idle inode is trivially drained.
        assert!(q.cycles_at_or_below_drained(99, Generation(0)));
    }

